/*
 * SwoftLang language server (LSP over Node IPC).
 *
 * Features:
 *   - Diagnostics: debounced `swoftc check` of the live buffer via a temp file.
 *   - Completion : keywords + declarations + operators + types + constants +
 *                  builtins + event names + property names (context-light).
 *   - Hover      : builtins (signature + doc) and properties (owner + type).
 *   - Document symbols: command / event / function / gui / scoreboard /
 *                  tablist / bossbar / mob / item declarations.
 *
 * The compiler prints `file:line:col: error|warning: msg` on stderr and
 * `{"error":{"message","line","col"}}` on stdout. line/col are 1-based; LSP
 * positions are 0-based, so we subtract one (clamped at 0).
 */
